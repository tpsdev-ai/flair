#!/usr/bin/env node
/**
 * vendor-tool-descriptors.mjs — flair#1683.
 *
 * `@tpsdev-ai/flair-tool-descriptors` is a *build-time* source, not a runtime
 * dependency. It is a private workspace package (never published — ops-evr7),
 * so declaring it in `dependencies` makes a fresh `npm install -g
 * @tpsdev-ai/flair` 404 on the registry; `bundleDependencies` "solved" that but
 * broke npm's reify against harper's own `npm-shrinkwrap.json` — the 0.54.1
 * shape, where a global install reported "invalid or damaged lockfile", added
 * 50 packages instead of 543, and left harper with no dependency tree at all.
 *
 * The fix is to stop needing it as a dependency. This script copies the
 * descriptor source (the single source of truth,
 * `packages/flair-tool-descriptors/src/index.ts`) verbatim into each consuming
 * package's own source tree at build time:
 *
 *   @tpsdev-ai/flair      → resources/tool-descriptors/index.ts
 *                           (tsconfig rootDir "." → dist/resources/tool-descriptors/index.js)
 *   @tpsdev-ai/flair-mcp  → packages/flair-mcp/src/tool-descriptors/index.ts
 *                           (tsconfig rootDir "src" → dist/tool-descriptors/index.js)
 *
 * Each consumer imports the vendored copy by RELATIVE path
 * (`./tool-descriptors/index.js`), which is what actually resolves inside the
 * packed tarball. Every build/test/typecheck path that consumes the descriptors
 * must run this first — see `prebuild` in both package.json files,
 * `scripts/test-unit.ts`, and the typecheck jobs in .github/workflows/test.yml.
 *
 * The vendored copies are gitignored (generated, never committed). Drift is
 * impossible: the body is byte-for-byte the source, and
 * `test/unit/vendored-tool-descriptors.test.ts` asserts that.
 *
 * Usage:
 *   node scripts/vendor-tool-descriptors.mjs                       # both consumers
 *   node scripts/vendor-tool-descriptors.mjs <destDir> [<destDir>...]  # explicit
 *   # <destDir> is repo-root-relative.
 *
 * Success logs go to stderr, never stdout: `npm pack --silent` captures stdout
 * as the tarball path, and a stray stdout line concatenates into it.
 *
 * Exit codes:
 *   0 — every requested destination was written
 *   1 — the descriptor source is missing/unreadable, or a destination failed
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Repo-relative path of the canonical descriptor source. */
export const DESCRIPTORS_SRC_REL = "packages/flair-tool-descriptors/src/index.ts";
/** Repo-relative path of the descriptor workspace package (private). */
export const DESCRIPTORS_PKG_REL = "packages/flair-tool-descriptors";

/** Vendored file name inside each destination directory. */
export const VENDORED_FILE = "index.ts";

/**
 * Every consumer that needs a vendored copy, as a repo-relative directory.
 * The default (no-arg) run vendors all of them.
 */
export const VENDOR_TARGETS = [
  "resources/tool-descriptors",
  "packages/flair-mcp/src/tool-descriptors",
];

const BANNER = [
  "// ⚠️  GENERATED FILE — DO NOT EDIT, DO NOT COMMIT (flair#1683).",
  `// Verbatim build-time copy of ${DESCRIPTORS_SRC_REL}, the single source of truth.`,
  "// Regenerated by scripts/vendor-tool-descriptors.mjs (see each package's",
  "// `prebuild`). Edit the source, not this copy.",
  "",
].join("\n");

/** Walk up from `from` until we find the repo root (the descriptor workspace package). */
export function findRepoRoot(from) {
  let dir = resolve(from);
  for (;;) {
    if (existsSync(join(dir, DESCRIPTORS_PKG_REL, "package.json"))) return dir;
    const parent = dirname(dir);
    if (parent === dir) {
      throw new Error(`cannot find ${DESCRIPTORS_PKG_REL}/package.json walking up from ${from}`);
    }
    dir = parent;
  }
}

/** The exact bytes written to every vendored copy. */
export function vendoredContent(repoRoot = findRepoRoot(process.cwd())) {
  const src = join(repoRoot, DESCRIPTORS_SRC_REL);
  if (!existsSync(src)) {
    throw new Error(`descriptor source missing at ${src} — cannot vendor (flair#1683)`);
  }
  return BANNER + readFileSync(src, "utf8");
}

/**
 * Write the vendored copy for one repo-relative destination directory.
 * Returns the absolute path written.
 */
export function vendorToolDescriptors(destRel, repoRoot = findRepoRoot(process.cwd())) {
  const destDir = join(repoRoot, destRel.replace(/\/+$/, ""));
  mkdirSync(destDir, { recursive: true });
  const dest = join(destDir, VENDORED_FILE);
  writeFileSync(dest, vendoredContent(repoRoot));
  return dest;
}

const thisFile = fileURLToPath(import.meta.url);
const invoked = process.argv[1] ? resolve(process.argv[1]) : "";
if (invoked && thisFile === invoked) {
  try {
    const repoRoot = findRepoRoot(process.cwd());
    const targets = process.argv.slice(2);
    const dests = targets.length ? targets : VENDOR_TARGETS;
    for (const dest of dests) {
      const written = vendorToolDescriptors(dest, repoRoot);
      console.error(`vendored ${DESCRIPTORS_SRC_REL} → ${written}`);
    }
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
